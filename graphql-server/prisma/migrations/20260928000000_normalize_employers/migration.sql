-- Match JavaScript's whitespace set, including non-breaking and Unicode spaces.
CREATE FUNCTION pg_temp.normalize_employer_name(name TEXT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE STRICT AS $function$
  SELECT btrim(regexp_replace(translate(lower(name), '.,', ''),
    U&'[\0009-\000D\0020\00A0\1680\2000-\200A\2028\2029\202F\205F\3000\FEFF]+', ' ', 'g'));
$function$;

CREATE TEMP TABLE employer_merge ON COMMIT DROP AS
WITH resolved AS (
  SELECT e.uuid, e."postalCode",
    COALESCE(a.matching_key, pg_temp.normalize_employer_name(e.name)) AS matching_key,
    COALESCE(a.display_name, e.name) AS display_name,
    e.name = a.display_name AS already_canonical
  FROM "Employer" e
  LEFT JOIN employer_aliases a ON a.alias = pg_temp.normalize_employer_name(e.name)
)
SELECT *, first_value(uuid) OVER (
  PARTITION BY matching_key, "postalCode"
  ORDER BY already_canonical DESC NULLS LAST, uuid
) AS survivor_uuid
FROM resolved;

UPDATE "LCADisclosure" d SET "employerUuid" = m.survivor_uuid
FROM employer_merge m WHERE d."employerUuid" = m.uuid AND m.uuid <> m.survivor_uuid;
-- Preserve legacy raw-data references as well as the application foreign keys.
UPDATE "RawDisclosureData" d SET "employerUuid" = m.survivor_uuid
FROM employer_merge m WHERE d."employerUuid" = m.uuid AND m.uuid <> m.survivor_uuid;

DELETE FROM "Employer" e USING employer_merge m
WHERE e.uuid = m.uuid AND m.uuid <> m.survivor_uuid;

DROP INDEX "Employer_name_postalCode_key";
UPDATE "Employer" e SET "normalizedName" = m.matching_key, name = m.display_name
FROM employer_merge m WHERE e.uuid = m.uuid AND m.uuid = m.survivor_uuid;
ALTER TABLE "Employer" ALTER COLUMN "normalizedName" SET NOT NULL;
CREATE UNIQUE INDEX "Employer_normalizedName_postalCode_key"
  ON "Employer"("normalizedName", "postalCode");
COMMIT;
